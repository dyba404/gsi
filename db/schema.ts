import { sql } from "drizzle-orm";
import { numeric, uuid, integer } from "drizzle-orm/pg-core";

export const producto = pgTable(
  "producto",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    tenantId: text("tenant_id").notNull(),
    sku: text("sku").notNull(),
    nombre: text("nombre").notNull(),
    categoria: text("categoria"),
    unidadMedida: text("unidad_medida").notNull().default("UND"),
    codigoBarras: text("codigo_barras"),
    stockMinimo: numeric("stock_minimo", { precision: 14, scale: 3 }).notNull().default("0"),
    stock: numeric("stock", { precision: 14, scale: 3 }).notNull().default("0"),
    costoPromedio: numeric("costo_promedio", { precision: 14, scale: 4 }).notNull().default("0"),
    activo: boolean("activo").notNull().default(true),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("producto_tenant_sku_uidx").on(t.tenantId, t.sku),
    index("producto_tenant_nombre_idx").on(t.tenantId, t.nombre),
  ],
);

export const movimiento = pgTable(
  "movimiento",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    tenantId: text("tenant_id").notNull(),
    productoId: uuid("producto_id")
      .notNull()
      .references(() => producto.id),
    tipo: text("tipo").notNull(),
    sentido: integer("sentido").notNull(),
    cantidad: numeric("cantidad", { precision: 14, scale: 3 }).notNull(),
    costoUnitario: numeric("costo_unitario", { precision: 14, scale: 4 }).notNull(),
    motivo: text("motivo"),
    nota: text("nota"),
    saldoDespues: numeric("saldo_despues", { precision: 14, scale: 3 }).notNull(),
    costoPromedioDespues: numeric("costo_promedio_despues", { precision: 14, scale: 4 }).notNull(),
    usuarioId: text("usuario_id").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("movimiento_producto_fecha_idx").on(t.productoId, t.createdAt),
    index("movimiento_tenant_fecha_idx").on(t.tenantId, t.createdAt),
  ],
);
